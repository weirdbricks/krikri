TEXT_SYMBOLS = ("codecs", "to_bytes", "to_text", "to_native", "binary_type",
                "text_type", "PY3")
ERRORS_SYMBOLS = ("_AnsibleActionDone", "AnsibleFilterTypeError")


def import_clause_names(clause, lines, index):
    names = []
    clause = clause.split("#", 1)[0]
    while index < len(lines) and (clause.count("(") > clause.count(")") or
                                  clause.rstrip().endswith("\\")):
        clause += " " + lines[index].split("#", 1)[0]
        index += 1
    for piece in clause.split(","):
        match = re.search(r"\b[A-Za-z_][A-Za-z0-9_]*", piece)
        if match:
            names.append(match.group(0))
    return names, index


def text_clause_events(clause, lines, index):
    names, index = import_clause_names(clause, lines, index)
    return [("text", name) for name in names if name in TEXT_SYMBOLS], index


def errors_clause_events(clause, lines, index):
    names, index = import_clause_names(clause, lines, index)
    return [("errors", name) for name in names if name in ERRORS_SYMBOLS], index


COMPAT_IMPORT = re.compile(r"^\s*import\s+ansible\.module_utils\.common\._collections_compat\b|"
                           r"^\s*from\s+ansible\.module_utils\.common\._collections_compat\s+import\b")
TEXT_IMPORT = re.compile(r"^\s*from\s+ansible\.module_utils\._text\s+import\s+(.+)$")
ERRORS_IMPORT = re.compile(r"^\s*from\s+ansible\.errors\s+import\s+(.+)$")
TYPE_CHECKING = re.compile(r"^(\s*)if\s+(?:typing\.)?TYPE_CHECKING\s*:")


def deprecated_import_events(source):
    """An action plugin's deprecated imports, in source order."""
    events = []
    lines = source.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        index += 1
        if COMPAT_IMPORT.match(line):
            events.append(("compat", ""))
            continue
        match = ERRORS_IMPORT.match(line)
        if match:
            clause_events, index = errors_clause_events(match.group(1), lines, index)
            events += clause_events
            continue
        match = TEXT_IMPORT.match(line)
        if match:
            clause_events, index = text_clause_events(match.group(1), lines, index)
            events += clause_events
    return events


def collection_module_utils_target(line, module_path, coll_dir):
    candidate = relative_import_target(line, module_path) or \
        absolute_collection_import_target(line, coll_dir)
    if not candidate or not os.path.isfile(candidate):
        return None
    if not os.path.dirname(candidate).startswith(os.path.join(coll_dir, "plugins", "module_utils")):
        return None
    return candidate


def relative_import_target(line, module_path):
    match = re.match(r"^\s*from\s+((?:\.)+)([\w.]*)\s+import\b", line)
    if not match or not match.group(2) or match.group(2).endswith("."):
        return None
    dotted = match.group(2).split(".")
    base = os.path.dirname(module_path)
    for _ in range(len(match.group(1)) - 1):
        base = os.path.dirname(base)
    parent = os.path.join(base, *dotted[:-1]) if len(dotted) > 1 else base
    return os.path.join(parent, dotted[-1] + ".py")


def absolute_collection_import_target(line, coll_dir):
    match = re.match(r"^\s*from\s+ansible_collections\.([\w.]+)\s+import\b", line) or \
        re.match(r"^\s*import\s+ansible_collections\.([\w.]+)\b", line)
    if not match:
        return None
    fq = "%s.%s" % (os.path.basename(os.path.dirname(coll_dir)), os.path.basename(coll_dir))
    remainder = match.group(1)
    if not remainder.startswith(fq + "."):
        return None
    remainder = remainder[len(fq) + 1:]
    if not remainder.startswith("plugins.module_utils."):
        return None
    return os.path.join(coll_dir, *remainder.replace(".", "/").split("/")) + ".py"


def payload_import_events(module_path, visited):
    if module_path in visited:
        return []
    visited.add(module_path)
    events = []
    coll_dir = payload_collection_root(module_path)
    lines = open(module_path, errors="replace").read().splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        index += 1
        match = TYPE_CHECKING.match(line)
        if match:
            indent = len(match.group(1))
            while index < len(lines):
                candidate = lines[index]
                if candidate.strip() and len(candidate) - len(candidate.lstrip()) <= indent:
                    break
                index += 1
            continue
        if COMPAT_IMPORT.match(line):
            events.append(("compat", ""))
            continue
        match = TEXT_IMPORT.match(line)
        if match:
            clause_events, index = text_clause_events(match.group(1), lines, index)
            events += clause_events
            continue
        if coll_dir:
            target = collection_module_utils_target(line, module_path, coll_dir)
            if target:
                events += payload_import_events(target, visited)
    return events


def payload_collection_root(module_path):
    """The ansible_collections/<ns>/<coll> directory a payload lives under
    (module files and their module_utils sit at different depths under it,
    so the prefix is located directly)."""
    parts = module_path.split(os.sep)
    if "ansible_collections" not in parts:
        return None
    index = len(parts) - 1 - parts[::-1].index("ansible_collections")
    if index + 2 >= len(parts):
        return None
    root = os.sep.join(parts[:index + 3])
    if module_path.startswith(os.sep) and not root.startswith(os.sep):
        root = os.sep + root
    return root


