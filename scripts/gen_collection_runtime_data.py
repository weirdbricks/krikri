#!/usr/bin/env python3
"""Regenerate src/krikri/collection_runtime_data.cr from a dev-time
ansible-core + collections tree.

krikri has no runtime dependency on an Ansible installation: this file is the
ONLY place its module-name resolution, collection release pinning, action
plugin inventory and module_utils deprecation data come from. Nothing in
src/ reads an installed ansible-core or ansible_collections tree at run time
(role/playbook `library/*.py` and collection python plugins are still
EXECUTED, which is plugin execution, not reference data).

Captured here, from the pinned capture environment:

* every collection visible to krikri's own collection search order (the same
  order `CollectionIndex.roots` uses): its MANIFEST.json release version, its
  meta/runtime.yml plugin_routing redirect tables, its action_groups, and -
  for the collections that provide one of the modules krikri implements
  natively - the relative file tree under plugins/{modules,action,lookup} so
  the name-resolution rules run against exactly what real's loader would see;
* the collection release each module krikri supports resolves to (its baked
  per-module collection version, the plugin wire's `collection_version`);
* every action plugin's deprecated ansible.module_utils / ansible.errors
  imports, so ModuleUtilsDeprecations can print real's lines without mining
  installed Python source at run time;
* the deprecated imports of each supported module's own payload (following
  its collection-internal module_utils import chain, in import order);
* the bare lookup names any visible collection provides.

The scanner functions below are a faithful port of what
src/krikri/module_utils_deprecations.cr used to do over installed sources at
run time (same order, same TYPE_CHECKING skip, same same-collection
module_utils following) - moving them here is what makes the run-time answer
independent of the machine.

Usage:
  python3 scripts/gen_collection_runtime_data.py             # rewrite the file
  python3 scripts/gen_collection_runtime_data.py --check     # verify it (exit 1 on drift)
  python3 scripts/gen_collection_runtime_data.py --ansible-pkg DIR
"""
