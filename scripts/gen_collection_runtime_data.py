# Module-name resolution over the captured collections (real's loader rules,
# the same ones CollectionIndex now applies against the baked tables).
# ---------------------------------------------------------------------------

MODULE_IGNORE_EXTS = (".pyc", ".pyo", ".swp", ".bak", "~", ".rpm", ".md",
                      ".txt", ".rst", ".yaml", ".yml", ".ini")
MAX_REDIRECT_HOPS = 12


def builtin_runtime(pkg):
    path = os.path.join(pkg, "config", "ansible_builtin_runtime.yml")
    routing = (yaml.safe_load(open(path)) or {}).get("plugin_routing") or {}
    tables = {"modules": {}, "action": {}, "lookup": {}}
    for kind in tables:
        for name, entry in (routing.get(kind) or {}).items():
            if isinstance(entry, dict):
                target = entry.get("redirect")
                if isinstance(target, str) and target.strip():
                    tables[kind][name] = target.strip()
    return tables


class Resolver:
    def __init__(self, pkg, dirs):
        self.pkg = pkg
        self.dirs = dirs
        self.builtin = builtin_runtime(pkg)
        self._redirects = {}

    def redirects(self, fq):
        if fq not in self._redirects:
            first = (self.dirs.get(fq) or [None])[0]
            self._redirects[fq] = redirect_tables(first) if first else {"modules": {}, "action": {}, "lookup": {}}
        return self._redirects[fq]

    def target(self, current):
        parts = current.split(".")
        if len(parts) == 1:
            return self.builtin["modules"].get(current)
        if parts[0] == "ansible" and parts[1] in ("builtin", "legacy"):
            leaf = ".".join(parts[2:])
            return self.builtin["modules"].get(leaf) if leaf else None
        leaf = ".".join(parts[2:])
        if not leaf:
            return None
        return self.redirects("%s.%s" % (parts[0], parts[1]))["modules"].get(leaf)

    def chain(self, name):
        current = name
        seen = {current}
        while len(seen) <= MAX_REDIRECT_HOPS:
            nxt = self.target(current)
            if not nxt or nxt in seen:
                break
            seen.add(nxt)
            current = nxt
        return current

    def module_file(self, name):
        """The payload file real's loader would execute for *name*, or None."""
        parts = self.chain(name).split(".")
        if len(parts) < 3:
            return None
        if parts[0] == "ansible" and parts[1] in ("builtin", "legacy"):
            path = os.path.join(self.pkg, "modules", *parts[2:]) + ".py"
            return path if os.path.isfile(path) else None
        first = (self.dirs.get("%s.%s" % (parts[0], parts[1])) or [None])[0]
        if not first:
            return None
        leaf = ".".join(parts[2:])
        path = os.path.join(first, "plugins", "modules", leaf + ".py")
        return path if os.path.isfile(path) else None

    def provider(self, name):
        """(collection, version) for the release whose payload *name*
        resolves to, or None when it resolves to ansible-core itself."""
        resolved = self.chain(name)
        parts = resolved.split(".")
        if len(parts) >= 3:
            if parts[0] == "ansible" and parts[1] in ("builtin", "legacy"):
                return None
            fq = "%s.%s" % (parts[0], parts[1])
            first = (self.dirs.get(fq) or [None])[0]
            return (fq, manifest_version(first) if first else None)
        for fq in sorted(self.dirs):
            for coll_dir in self.dirs[fq]:
                candidate = os.path.join(coll_dir, "plugins", "modules", resolved + ".py")
                if os.path.isfile(candidate):
                    return (fq, manifest_version(self.dirs[fq][0]))
        return None


def krikri_modules():
    """AVAILABLE_PLUGINS plus every MODULE_ALIASES spelling, the names this
    engine can actually run."""
    src = open(REGISTRY).read()
    match = re.search(r"AVAILABLE_PLUGINS = Set\{(.*?)\n    \}", src, re.S)
    assert match, "AVAILABLE_PLUGINS block not found"
    names = set(re.findall(r'"([a-z0-9_]+\.[a-z0-9_.]+)"', match.group(1)))
    alias = re.search(r"MODULE_ALIASES = \{(.*?)\n    \}", src, re.S)
    if alias:
        for key, value in re.findall(r'"([a-z0-9_.]+)"\s*=>\s*"([a-z0-9_.]+)"',
                                     alias.group(1)):
            names.add(key)
            names.add(value)
    if os.path.isfile(ARGSPECS):
        names |= set(json.load(open(ARGSPECS)))
    return sorted(names)


# ---------------------------------------------------------------------------
# Deprecated ansible.module_utils import scanning (ported from what
# module_utils_deprecations.cr did over installed sources at run time).
