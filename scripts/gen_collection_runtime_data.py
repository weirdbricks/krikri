def lookup_provider_names(dirs, resolver):
    """Bare lookup names the captured collections provide: a
    plugins/lookup/<name>.py file, or a lookup routing redirect whose chain
    lands on one."""
    provided = set()
    for fq in sorted(dirs):
        for coll_dir in dirs[fq]:
            base = os.path.join(coll_dir, "plugins", "lookup")
            if os.path.isdir(base):
                for name in os.listdir(base):
                    if name.endswith(".py"):
                        provided.add(name[:-3])
        for name in resolver.redirects(fq)["lookup"]:
            if chain_provides_lookup(resolver, resolver.redirects(fq)["lookup"][name], set()):
                provided.add(name)
    return sorted(provided)


def chain_provides_lookup(resolver, fqcn, seen):
    if fqcn in seen:
        return False
    seen.add(fqcn)
    parts = fqcn.split(".")
    if len(parts) < 3:
        return False
    for coll_dir in resolver.dirs.get("%s.%s" % (parts[0], parts[1]), []):
        leaf = ".".join(parts[2:])
        if os.path.isfile(os.path.join(coll_dir, "plugins", "lookup", leaf + ".py")):
            return True
    table = resolver.redirects("%s.%s" % (parts[0], parts[1]))["lookup"]
    leaf = ".".join(parts[2:])
    if leaf in table:
        return chain_provides_lookup(resolver, table[leaf], seen)
    return False


def collect(pkg, ansible_version):
    dirs = collection_dirs()
    resolver = Resolver(pkg, dirs)
    module_names = krikri_modules()

    module_versions = {}
    module_scope = set()
    for name in module_names:
        provider = resolver.provider(name)
        if not provider:
            continue
        fq, version = provider
        module_scope.add(fq)
        module_versions[name] = {"collection": fq,
                                 "version": version or ""}

    collections = {}
    for fq in sorted(dirs):
        first = dirs[fq][0]
        entry = {
            "version": manifest_version(first),
            "redirects": redirect_tables(first),
            "action_groups": action_groups(first),
        }
        if fq in module_scope:
            entry["paths"] = plugin_paths(first)
        collections[fq] = entry

    # Every action plugin the captured collections (and ansible-core) ship,
    # with the deprecated imports each one makes: real loads a task's action
    # plugin even when the task is skipped, so its lines print for modules
    # krikri has no file tree for too.
    action_plugins = {}
    action_plugins["ansible.builtin"] = {}
    builtin_action_dir = os.path.join(pkg, "plugins", "action")
    if os.path.isdir(builtin_action_dir):
        for name in sorted(os.listdir(builtin_action_dir)):
            if name.endswith(".py") and not name.startswith("_"):
                source = open(os.path.join(builtin_action_dir, name), errors="replace").read()
                action_plugins["ansible.builtin"][name[:-3]] = [list(event) for event in deprecated_import_events(source)]
    for fq in sorted(dirs):
        action_dir = os.path.join(dirs[fq][0], "plugins", "action")
        if not os.path.isdir(action_dir):
            continue
        per_collection = {}
        for name in sorted(os.listdir(action_dir)):
            if name.endswith(".py") and not name.startswith("_"):
                source = open(os.path.join(action_dir, name), errors="replace").read()
                per_collection[name[:-3]] = [list(event) for event in deprecated_import_events(source)]
        action_plugins[fq] = per_collection

    module_deprecations = {}
    for name in module_names:
        path = resolver.module_file(name)
        if not path:
            continue
        module_deprecations[name] = [list(event) for event in payload_import_events(path, set())]

    data = {
        "ansible_core_version": ansible_version,
        "known_collections": sorted(dirs),
        "collections": collections,
        "action_plugins": action_plugins,
        "module_versions": module_versions,
        "module_deprecations": module_deprecations,
        "lookup_providers": lookup_provider_names(dirs, resolver),
    }
    return data


def encode(value):
    raw = json.dumps(value, separators=(",", ":"), sort_keys=True, ensure_ascii=False).encode()
    return base64.b64encode(gzip.compress(raw, compresslevel=9, mtime=0)).decode()


def wrap(blob):
    return "\n".join("    " + blob[i:i + BASE64_WIDTH] for i in range(0, len(blob), BASE64_WIDTH))


def render(version, data):
    return (HEADER.format(version=version, count=len(data["collections"]),
                          module_count=len(data["module_versions"]))
            + wrap(encode(data)) + "\n    GZB64\n\n" + FOOTER)


def decode_blob(source):
    blobs = re.findall(r"<<-GZB64\n(.*?)\n\s*GZB64", source, re.S)
    if len(blobs) != 1:
        sys.exit("expected 1 embedded blob in %s, found %d" % (OUT, len(blobs)))
    return json.loads(gzip.decompress(base64.b64decode(re.sub(r"\s", "", blobs[0]))))


def main():
    args = sys.argv[1:]
    check = "--check" in args
    pkg = None
    if "--ansible-pkg" in args:
        pkg = args[args.index("--ansible-pkg") + 1]
    pkg = pkg or discover_package()
    version = package_version(pkg)
    data = collect(pkg, version)

    if check:
        if not os.path.isfile(OUT):
            print("missing %s" % OUT, file=sys.stderr)
            return 1
        have = decode_blob(open(OUT).read())
        drift = []
        for key in sorted(data):
            if have.get(key) != data[key]:
                drift.append(key)
        if drift:
            print("%s is stale (drifted sections: %s)" % (OUT, ", ".join(drift)), file=sys.stderr)
            for key in drift:
                was, now = have.get(key), data[key]
                if isinstance(now, dict):
                    added = sorted(set(now) - set(was or {}))
                    removed = sorted(set(was or {}) - set(now))
                    if added:
                        print("  %s: +%d entries (e.g. %s)" % (key, len(added), ", ".join(added[:5])), file=sys.stderr)
                    if removed:
                        print("  %s: -%d entries (e.g. %s)" % (key, len(removed), ", ".join(removed[:5])), file=sys.stderr)
            print("rerun: python3 scripts/gen_collection_runtime_data.py", file=sys.stderr)
            return 1
        print("%s matches the captured ansible-core %s environment" % (OUT, version))
        return 0

    with open(OUT, "w") as handle:
        handle.write(render(version, data))
    print("wrote %s (%d collections, %d modules)" % (OUT, len(data["collections"]),
                                                     len(data["module_versions"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
