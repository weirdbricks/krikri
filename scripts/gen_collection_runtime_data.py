# ---------------------------------------------------------------------------
# The capture environment: krikri's own collection search order, minus the
# ansible-playbook shebang hop that used to make it machine-dependent.
# ---------------------------------------------------------------------------

def _glob_dirs(pattern):
    return sorted(d for d in glob.glob(pattern) if os.path.isdir(d))


def package_bases(home):
    bases = []
    for prefix in ("/usr/lib", "/usr/local/lib", "/opt"):
        for pydir in _glob_dirs("%s/python3*" % prefix):
            for leaf in ("dist-packages", "site-packages"):
                candidate = os.path.join(pydir, leaf)
                if os.path.isdir(candidate):
                    bases.append(candidate)
    if home:
        for candidate in _glob_dirs(os.path.join(home, ".local", "lib", "python3*", "site-packages")):
            bases.append(candidate)
    return bases


def search_roots():
    """Every directory that CONTAINS an ansible_collections tree, in krikri's
    own order: ANSIBLE_COLLECTIONS_PATH (unset at capture time), the user and
    system install locations, then the python package dirs."""
    roots = []
    env = os.environ.get("ANSIBLE_COLLECTIONS_PATH") or os.environ.get("ANSIBLE_COLLECTIONS_PATHS")
    if env:
        for entry in env.split(":"):
            if entry:
                roots.append(entry.rstrip("/"))
    home = os.environ.get("HOME")
    if home:
        roots.append(os.path.join(home, ".ansible", "collections"))
    roots.append("/usr/share/ansible/collections")
    for base in package_bases(home):
        candidate = os.path.join(base, "ansible_collections")
        if os.path.isdir(candidate):
            roots.append(candidate)
    return roots


def collection_dirs():
    """'ns.coll' => existing directories, FIRST copy first (real's loader
    reads only that one)."""
    dirs = {}
    for root in search_roots():
        for tree in (os.path.join(root, "ansible_collections"), root):
            if not (os.path.isdir(tree) and os.path.basename(tree) == "ansible_collections"):
                continue
            for namespace in sorted(os.listdir(tree)):
                ns_dir = os.path.join(tree, namespace)
                if namespace.startswith(".") or not os.path.isdir(ns_dir):
                    continue
                for collection in sorted(os.listdir(ns_dir)):
                    coll_dir = os.path.join(ns_dir, collection)
                    if collection.startswith(".") or not os.path.isdir(coll_dir):
                        continue
                    dirs.setdefault("%s.%s" % (namespace, collection), []).append(coll_dir)
    return dirs


def discover_package():
    code = "import ansible, os; print(os.path.dirname(ansible.__file__))"
    import subprocess
    out = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit("no ansible-core importable by %s (pass --ansible-pkg)" % sys.executable)
    return out.stdout.strip()


def package_version(pkg):
    release = os.path.join(pkg, "release.py")
    if os.path.isfile(release):
        match = re.search(r'__version__\s*=\s*[\'"]([^\'"]+)', open(release).read())
        if match:
            return match.group(1)
    sys.exit("could not read the ansible-core version from %s" % release)


def manifest_version(coll_dir):
    path = os.path.join(coll_dir, "MANIFEST.json")
    if not os.path.isfile(path):
        return None
    try:
        info = json.load(open(path)).get("collection_info") or {}
        return info.get("version")
    except Exception:  # noqa: BLE001 - an unreadable manifest reports nil
        return None


def redirect_tables(coll_dir):
    path = os.path.join(coll_dir, "meta", "runtime.yml")
    tables = {"modules": {}, "action": {}, "lookup": {}}
    if not os.path.isfile(path):
        return tables
    try:
        routing = (yaml.safe_load(open(path)) or {}).get("plugin_routing") or {}
    except Exception:  # noqa: BLE001
        return tables
    for kind in tables:
        entries = routing.get(kind) or {}
        for name, entry in entries.items():
            if isinstance(entry, dict):
                target = entry.get("redirect")
                if isinstance(target, str) and target.strip():
                    tables[kind][name] = target.strip()
    return tables


def action_groups(coll_dir):
    path = os.path.join(coll_dir, "meta", "runtime.yml")
    groups = {}
    if not os.path.isfile(path):
        return groups
    try:
        parsed = yaml.safe_load(open(path)) or {}
    except Exception:  # noqa: BLE001
        return groups
    for name, entries in (parsed.get("action_groups") or {}).items():
        members = []
        extends = []
        for entry in entries or []:
            if isinstance(entry, str):
                members.append(entry)
            elif isinstance(entry, dict):
                metadata = entry.get("metadata") or {}
                for target in metadata.get("extend_group") or []:
                    if isinstance(target, str):
                        extends.append(target)
        groups[name] = {"members": members, "extends": extends}
    return groups


def plugin_paths(coll_dir):
    out = []
    for kind in ("modules", "action", "lookup"):
        base = os.path.join(coll_dir, "plugins", kind)
        for root, _dirs, files in os.walk(base):
            for name in files:
                full = os.path.join(root, name)
                rel = os.path.relpath(full, coll_dir).replace(os.sep, "/")
                out.append(rel)
    return sorted(out)


