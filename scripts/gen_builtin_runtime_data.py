#!/usr/bin/env python3
"""Regenerate src/krikri/builtin_module_names_data.cr from an ansible-core
install.

That file carries the data CollectionIndex falls back to when the controller
has NO ansible-core installed (krikri replaces it there): the builtin
bare-name set and ansible_builtin_runtime.yml's module/action redirect
tables. It is version data, so it must be generated against
ANSIBLE_TARGET_VERSION (src/krikri/version.cr), not whatever happens to be
on the machine.

The live install still wins when one is discoverable - the baked tables are
the fallback, and the same data keeps the no-ansible-core path byte-identical
to a controller that has the package.

Usage:
  python3 scripts/gen_builtin_runtime_data.py             # rewrite the file
  python3 scripts/gen_builtin_runtime_data.py --check     # verify it (exit 1 on drift)
  python3 scripts/gen_builtin_runtime_data.py --ansible-pkg DIR
"""
import base64
import glob
import gzip
import json
import os
import re
import subprocess
import sys

try:
    import yaml
except ImportError:
    sys.exit("PyYAML is required (it ships with ansible-core)")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "src", "krikri", "builtin_module_names_data.cr")
BASE64_WIDTH = 96

HEADER = '''require "base64"
require "compress/gzip"
require "json"

module Krikri
  # The ansible-core {version} builtin bare-name set ({count} names: the
  # modules/ dir files plus every plugin_routing.modules redirect key, minus
  # tombstones) and its module/action redirect tables - GPLv3 data from the
  # same release family, embedded so the controller-resolution check works on
  # a controller with NO ansible-core installed (krikri replaces it).
  # Gzipped base64, decompressed lazily once per process.
  #
  # Generated by scripts/gen_builtin_runtime_data.py - do not hand-edit; run
  # it after a target ansible-core bump (its --check verifies this file).
  private BUILTIN_DATA_GZ = <<-GZB64
'''

FOOTER = '''  private def self.decode_data(gz : String) : String
    Compress::Gzip::Reader.open(IO::Memory.new(Base64.decode(gz.gsub(/\\s/, "")))) do |reader|
      reader.gets_to_end
    end
  end

  def self.builtin_module_names : Array(String)
    Array(String).from_json(decode_data(BUILTIN_DATA_GZ))
  end

  def self.builtin_runtime_redirects : {Hash(String, String), Hash(String, String)}
    data = JSON.parse(decode_data(REDIRECTS_DATA_GZ))
    mods = Hash(String, String).new
    data["modules"].as_h.each { |k, v| mods[k] = v.as_s }
    acts = Hash(String, String).new
    data["action"].as_h.each { |k, v| acts[k] = v.as_s }
    {mods, acts}
  end
end
'''


def discover_package() -> str:
    code = "import ansible, os; print(os.path.dirname(ansible.__file__))"
    out = subprocess.run([sys.executable, "-c", code],
                         capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit("no ansible-core importable by %s (pass --ansible-pkg)" % sys.executable)
    return out.stdout.strip()


def package_version(pkg: str) -> str:
    release = os.path.join(os.path.dirname(pkg), "ansible", "release.py")
    if not os.path.isfile(release):
        release = os.path.join(pkg, "release.py")
    if os.path.isfile(release):
        match = re.search(r'__version__\s*=\s*[\'"]([^\'"]+)', open(release).read())
        if match:
            return match.group(1)
    sys.exit("could not read the ansible-core version from %s" % release)


def redirect_table(routing: dict, kind: str) -> dict:
    entries = routing.get(kind) or {}
    table = {}
    for name, entry in entries.items():
        if not isinstance(entry, dict):
            continue
        target = entry.get("redirect")
        if isinstance(target, str) and target.strip():
            table[name] = target.strip()
    return table


def collect(pkg: str):
    files = {os.path.splitext(os.path.basename(path))[0]
             for path in glob.glob(os.path.join(pkg, "modules", "**", "*.py"),
                                   recursive=True)}
    builtin_tree = os.path.join(os.path.dirname(pkg), "ansible_collections",
                                "ansible", "builtin", "plugins", "modules")
    files |= {os.path.splitext(os.path.basename(path))[0]
              for path in glob.glob(os.path.join(builtin_tree, "*.py"))}

    runtime = os.path.join(pkg, "config", "ansible_builtin_runtime.yml")
    routing = (yaml.safe_load(open(runtime)) or {}).get("plugin_routing") or {}
    modules = redirect_table(routing, "modules")
    action = redirect_table(routing, "action")
    # Tombstones are deliberately not part of the name set: a removed name is
    # REMOVED_MODULE_TOMBSTONES' job, this set only says where a module file
    # really is. Plugin_routing.modules' redirect keys ARE included even
    # though the live scan only globs files - builtin_module? subtracts them
    # again so the baked answer matches the live one exactly.
    names = sorted(files | set(modules))
    return names, {"modules": modules, "action": action}


def encode(value) -> str:
    raw = json.dumps(value, separators=(",", ":"), ensure_ascii=False).encode()
    return base64.b64encode(gzip.compress(raw, compresslevel=9, mtime=0)).decode()


def wrap(blob: str) -> str:
    return "\n".join("    " + blob[i:i + BASE64_WIDTH]
                     for i in range(0, len(blob), BASE64_WIDTH))


def render(version: str, names, redirects) -> str:
    return (HEADER.format(version=version, count=len(names))
            + wrap(encode(names)) + "\n    GZB64\n\n"
            + "  private REDIRECTS_DATA_GZ = <<-GZB64\n"
            + wrap(encode(redirects)) + "\n    GZB64\n\n"
            + FOOTER)


def decode_blobs(source: str):
    blobs = re.findall(r"<<-GZB64\n(.*?)\n\s*GZB64", source, re.S)
    if len(blobs) != 2:
        sys.exit("expected 2 embedded blobs in %s, found %d" % (OUT, len(blobs)))
    decoded = [gzip.decompress(base64.b64decode(re.sub(r"\s", "", blob)))
               for blob in blobs]
    return json.loads(decoded[0]), json.loads(decoded[1])


def main() -> int:
    args = sys.argv[1:]
    check = "--check" in args
    pkg = None
    if "--ansible-pkg" in args:
        pkg = args[args.index("--ansible-pkg") + 1]
    pkg = pkg or discover_package()
    version = package_version(pkg)
    names, redirects = collect(pkg)

    if check:
        if not os.path.isfile(OUT):
            print("missing %s" % OUT, file=sys.stderr)
            return 1
        have_names, have_redirects = decode_blobs(open(OUT).read())
        drift = []
        if have_names != names:
            only_file = sorted(set(names) - set(have_names))
            only_baked = sorted(set(have_names) - set(names))
            drift.append("names differ (%d in ansible-core %s, %d baked; +%s -%s)"
                         % (len(names), version, len(have_names),
                            only_file[:5], only_baked[:5]))
        for kind in ("modules", "action"):
            if have_redirects.get(kind) != redirects[kind]:
                drift.append("%s redirects differ (%d in ansible-core %s, %d baked)"
                             % (kind, len(redirects[kind]), version,
                                len(have_redirects.get(kind) or {})))
        if drift:
            print("baked data is stale against ansible-core %s:" % version, file=sys.stderr)
            for line in drift:
                print("  " + line, file=sys.stderr)
            return 1
        print("baked data matches ansible-core %s (%d names, %d/%d redirects)"
              % (version, len(names), len(redirects["modules"]),
                 len(redirects["action"])))
        return 0

    target = os.path.join(REPO, "src", "krikri", "version.cr")
    declared = re.search(r'ANSIBLE_TARGET_VERSION\s*=\s*"([^"]+)"', open(target).read())
    if declared and declared.group(1) != version:
        print("warning: ansible-core %s does not match ANSIBLE_TARGET_VERSION %s"
              % (version, declared.group(1)), file=sys.stderr)

    with open(OUT, "w") as handle:
        handle.write(render(version, names, redirects))
    print("wrote %s from ansible-core %s (%d names, %d module / %d action redirects)"
          % (os.path.relpath(OUT, REPO), version, len(names),
             len(redirects["modules"]), len(redirects["action"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
